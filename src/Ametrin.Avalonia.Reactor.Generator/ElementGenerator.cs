using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Ametrin.Avalonia.Reactor.Generator;

[Generator]
public sealed class ElementGenerator : IIncrementalGenerator
{
    private const string Header = "// <auto-generated/>\n#nullable enable\n\nnamespace Ametrin.Avalonia.Reactor;\n\n";
    private const string Element = "global::Ametrin.Avalonia.Reactor.Element";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var model = context.CompilationProvider.Select(static (compilation, token) => ModelBuilder.Build(compilation, token));
        context.RegisterSourceOutput(model, static (output, model) => Emit(output, model));
    }

    private static void Emit(SourceProductionContext output, GenerationModel model)
    {
        if (model.Controls.IsEmpty) return;
        output.AddSource("UI.Controls.g.cs", SourceText.From(EmitFactories(model), Encoding.UTF8));
        foreach (var owner in model.Owners)
        {
            output.CancellationToken.ThrowIfCancellationRequested();
            output.AddSource($"{owner.ClassName}.g.cs", SourceText.From(EmitOwner(owner), Encoding.UTF8));
        }
    }

    private static string EmitFactories(GenerationModel model)
    {
        var source = new StringBuilder(Header).AppendLine("public static partial class UI").AppendLine("{");
        foreach (var control in model.Controls)
        {
            var element = $"global::Ametrin.Avalonia.Reactor.ControlElement<{control.TypeName}>";
            source.AppendLine($"    public static {element} {control.Name}() => new();");
            switch (control.Kind)
            {
                case ChildKind.Panel:
                    source.AppendLine($"    public static {element} {control.Name}(params global::System.ReadOnlySpan<{Element}> children) => new {element}().Children(children);");
                    break;
                case ChildKind.Content:
                    source.AppendLine($"    public static {element} {control.Name}({Element} child) => new {element}().Children(child);");
                    source.AppendLine($"    public static {element} {control.Name}(object? content) => new {element}().Set(global::Avalonia.Controls.ContentControl.ContentProperty, content);");
                    break;
                case ChildKind.Decorator:
                    source.AppendLine($"    public static {element} {control.Name}({Element} child) => new {element}().Children(child);");
                    break;
            }
            if (control.TextProperty is { } text)
                source.AppendLine($"    public static {element} {control.Name}(string? text) => new {element}().Set({text}, text);");
        }
        return source.AppendLine("}").ToString();
    }

    private static string EmitOwner(OwnerModel owner)
    {
        var source = new StringBuilder(Header).AppendLine($"public static class {owner.ClassName}").AppendLine("{");
        var signature = $"this {owner.Receiver} element";
        foreach (var property in owner.Properties)
        {
            source.AppendLine($"    public static {owner.Receiver} {property.Name}{owner.TypeParameters}({signature}, {property.ValueType} value){owner.Constraint} => element.Set({property.Field}, value);");
            source.AppendLine($"    public static {owner.Receiver} {property.Name}{owner.TypeParameters}({signature}, {property.ValueType} value, global::System.Action<{property.ValueType}> onChanged){owner.Constraint} => element.Set({property.Field}, value).OnChanged({property.Field}, onChanged);");
        }
        foreach (var evt in owner.Events)
        {
            source.AppendLine($"    public static {owner.Receiver} {evt.Name}{owner.TypeParameters}({signature}, global::System.Action<{evt.ValueType}> handler){owner.Constraint} => element.On({evt.Field}, handler);");
            source.AppendLine($"    public static {owner.Receiver} {evt.Name}{owner.TypeParameters}({signature}, global::System.Action handler){owner.Constraint} => element.On({evt.Field}, _ => handler());");
        }
        return source.AppendLine("}").ToString();
    }
}
